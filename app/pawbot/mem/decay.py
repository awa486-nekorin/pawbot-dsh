"""渐忘：记忆按年龄降分辨率，但骨架永不消失。

## 为什么单独一个模块

用户的原话是「时间越久就越忘记但是又不能全忘记」。这句话拆开是两件相反的事：

  · 越久越忘  → 细节要掉
  · 不能全忘  → 骨架不能掉

现有的实现（`_score` 里的 `0.5 ** (age / 半衰)`）只做了前者的一半：它衰减的是**召回概率**
（分数变小、排到后面、可能不注入），但**一旦召回，内容是完整精确的全文**。
所以「三个月前那件事」要么被原样端出来，要么完全不出现 —— 中间那档「记得有这么回事、
但细节模糊」根本不存在。

这个模块补的就是中间那档。

## 四档

| 档 | 普通 | 重要(imp≥4) | 注入什么 | 数据来源 |
|---|---|---|---|---|
| 清晰 | 0~7 天 | 0~21 天 | 全文 | `text` |
| 略糊 | 7~30 天 | 21~90 天 | 骨架 + 一个要点，时间抹成「那阵子」 | `gist` + `points[0]` |
| 骨架 | 30~180 天 | 90~365 天 | 一句话 | `gist` |
| 影影绰绰 | >180 天 | >365 天 | 一句话 + 「细节记不清」 | `gist` |

**重要度把每一档的年龄阈值拉长 3 倍**：约定、承诺、关系这类东西掉得慢。
但**任何一档都不会降到空**——最老的那档仍然有一句话。这就是「不能全忘」。

## 为什么骨架要模型给，不能用规则

拿真实记忆库试过两版规则实现，都失败在同一处：

    原文：群里仍以图片和转发记录闲聊为主。炸金美墨先发《蔚蓝档案》一之濑明日奈趴床图，…
    规则产出：图片和转发记录闲聊为主          ← 把背景语当成了主干

根因是「哪一句是主干」需要理解语义，正则做不到。规则版能做的安全操作只有
**抹掉细节**（时间、括注、程度副词），**选主干是危险操作**——选错就等于说错事，
比不说更糟。

所以分工是：

  · 写入时由模型给 `gist`（一句话主干）和 `points`（2~3 个要点）—— 那时模型本来就在提炼，几乎零额外成本
  · 注入时按年龄选档，规则只负责抹细节
  · `gist` 缺失时**降级为截断**（取第一个句号前的内容），不猜主干 —— 说不全可以接受，说错不行

## 存储契约

`EntityStore` 的记录可以带三个可选字段，缺了也能正常工作：

    {"text": "全文", "gist": "一句话主干", "points": ["要点1", "要点2"]}

`gist` 只写一次（写入时），之后不变；`text` 也不变。**降分辨率只发生在注入时**，
所以原始数据永远完整，随时能「想起来更多」。
"""

from __future__ import annotations

import re

# ---------------------------------------------------------------- 档位

档位表 = [
    # 档名,     普通上限(天), 重要上限(天)
    ("清晰", 7, 21),
    ("略糊", 30, 90),
    ("骨架", 180, 365),
    ("影影绰绰", float("inf"), float("inf")),
]

重要度门槛 = 4          # imp >= 4 算「重要」，阈值 ×3
重要倍数 = 3.0

_档序 = [x[0] for x in 档位表]


def 取档(age_days: float, importance: int = 3) -> str:
    """按年龄和重要度决定分辨率。永不返回空档。"""
    龄 = max(0.0, float(age_days or 0))
    重要 = int(importance or 3) >= 重要度门槛
    for 名, 普, 重 in 档位表:
        if 龄 <= (重 if 重要 else 普):
            return 名
    return "影影绰绰"


def 档位说明(档: str) -> str:
    return {
        "清晰": "全文",
        "略糊": "骨架 + 一个要点，时间模糊",
        "骨架": "只剩一句话",
        "影影绰绰": "只剩一句话，且明说记不清",
    }.get(档, "")


# ---------------------------------------------------------------- 抹细节（安全操作）

_时间 = re.compile(
    r"\d{1,2}[:：]\d{2}|"
    r"(?:\d{4}\s*[-/.]\s*)?\d{1,2}\s*[-/.]\s*\d{1,2}(?:\s*[-/.]\s*\d{2,4})?|"   # 2026-09-17 / 09-17 / 9/17
    r"(?:今天|昨天|前天|明天|后天|大后天|今早|昨晚|今儿|明儿|刚才|刚刚|上周|下周|这周|"
    r"上个月|下个月|去年|前年|\d{1,2}\s*月\s*\d{1,2}\s*[日号]|\d{1,2}\s*月|\d{1,2}\s*[日号]|"
    r"周[一二三四五六日天]|星期[一二三四五六日天])"
)
_括注 = re.compile(r"[（(][^）)]{0,20}[）)]")
_程度 = re.compile(r"(非常|特别|有点|挺|很|太|超|极其|相当|稍微|略微|格外|十分)")


def 抹时间(文本: str) -> str:
    """把精确时间换成「那阵子」。只换时间，不动内容。"""
    t = _时间.sub("那阵子", str(文本 or ""))
    t = re.sub(r"(那阵子[，、]?\s*){2,}", "那阵子", t)
    return re.sub(r"\s{2,}", " ", t).strip()


def 抹细节(文本: str, *, 去括注: bool = True, 去程度: bool = True) -> str:
    """抹掉不影响「发生了什么」的修饰。"""
    t = str(文本 or "")
    if 去括注:
        t = _括注.sub("", t)
    t = 抹时间(t)
    if 去程度:
        t = _程度.sub("", t)
    return re.sub(r"\s{2,}", " ", t).strip("，、； ")


def 截首句(文本: str, 上限: int = 60) -> str:
    """兜底：取第一句。**不猜主干**——说不全可以接受，说错不行。"""
    t = str(文本 or "").strip()
    if not t:
        return ""
    句 = re.split(r"[。！？；]", t, maxsplit=1)
    s = 句[0].strip("，、； ")
    if len(s) > 上限:
        # 按逗号截，别把半句留成断头
        块 = re.split(r"[，,]", s)
        累 = ""
        for x in 块:
            if len(累) + len(x) + 1 > 上限:
                break
            累 = (累 + "，" + x) if 累 else x
        s = 累 or s[:上限]
    return s


# ---------------------------------------------------------------- 渲染

_模糊前缀 = "（过去挺久了，细节记不清）"


def 渲染(row: dict, age_days: float, *, 前缀: bool = True) -> str:
    """按年龄把一条记忆渲染成该有的粒度。

    row 至少要有 text；有 gist 时用 gist（准），没有就截首句（安全）。
    """
    全文 = str(row.get("text") or "").strip()
    gist = str(row.get("gist") or "").strip()
    档 = 取档(age_days, row.get("importance") or 3)

    if 档 == "清晰":
        # 压实过的记录 text 会被清掉（只留 gist），这时拿 gist 顶上——**不许因为压实就丢内容**
        return 全文 or gist

    要点 = row.get("points") or []
    要点 = [str(x).strip() for x in 要点 if str(x or "").strip()]

    if 档 == "略糊":
        if gist:
            出 = 抹时间(gist)
            if 要点:
                出 += "。" + 抹细节(要点[0])
            return 出
        # 没有骨架：全文抹细节（保留全部事件，只是时间糊了）
        return 抹细节(全文)

    # 骨架 / 影影绰绰
    主干 = gist or 截首句(抹细节(全文))
    if not 主干:
        return ""
    if 档 == "影影绰绰":
        # 最老那档再掉一层：只留第一个分句（把评价、态度也掉掉，只剩「发生过什么」）
        半 = re.split(r"[，,。；;]", 主干)[0].strip("，、； ")
        return (_模糊前缀 + (半 or 主干)) if 前缀 else (半 or 主干)
    return 主干


def 需要补骨架(row: dict, age_days: float) -> bool:
    """这条该不该补 gist —— 只在真要降档、且还没骨架时才需要，别白花模型钱。"""
    if str(row.get("gist") or "").strip():
        return False
    if not str(row.get("text") or "").strip():
        return False
    return 取档(age_days, row.get("importance") or 3) != "清晰"


def 时间措辞(age_days: float, 档: str | None = None) -> str:
    """时间说法也要跟着糊。真人不会说「200 天前」，会说「好像挺久了」。

    清晰档给精确值（这是「刚发生」的实感），越往后越含糊，最老那档干脆不给。
    """
    龄 = max(0.0, float(age_days or 0))
    档 = 档 or 取档(龄)
    if 档 == "清晰":
        if 龄 < 1 / 24:
            return "刚才"
        if 龄 < 1:
            return f"{int(龄 * 24)} 小时前"
        return f"{int(龄)} 天前"
    if 档 == "略糊":
        return "那阵子"
    if 档 == "骨架":
        return "几个月前"
    return ""          # 影影绰绰：前缀已经交代了，不再报时间（1 年和 10 年都是「过去挺久了」）


# ---------------------------------------------------------------- 给模型的提示词

骨架提示词 = """把下面这段聊天记忆压成两样东西，只输出 JSON，不要解释。

要压的内容：
{正文}

输出格式：
{{"gist": "一句话主干", "points": ["要点一", "要点二"]}}

规矩：
- gist 说清「谁 + 做了什么 + 结果」，**不超过 40 字**，不要时间词（不写「今天」「周三」「9月17日」）
- points 是 2~3 个次要细节，每条不超过 30 字；没有就少写几条
- **不许编**：只压缩，不补充原文没有的信息
- 不许写「这段记忆讲了……」这种元叙述，直接说事
- 人名保留原样，不要换成「有人」「对方」"""


def 骨架提示(正文: str) -> str:
    return 骨架提示词.format(正文=str(正文 or "")[:1200])
